using System.Reflection;
using Ordering.Domain.Orders;
using SharedKernel.Domain;
using SharedKernel.Events;

namespace Ordering.Application.UnitTests.Orders;

internal static class TestOrders
{
    public const long OrderId = 5;
    public const long UserId = 7;
    public const long OtherUserId = 8;
    public const long KeyboardId = 10;
    public const long MouseId = 20;
    public const string CustomerCancelReason = "Changed my mind";

    public static readonly DateTime CreatedOnUtc = new(2026, 1, 1, 9, 0, 0, DateTimeKind.Utc);
    public static readonly DateTime UtcNow = new(2026, 1, 2, 10, 0, 0, DateTimeKind.Utc);

    private static readonly PropertyInfo IdProperty = typeof(Entity<long>).GetProperty(nameof(Entity<long>.Id))!;

    // 2 keyboards at 10 USD and 3 mice at 5 USD: total 35 USD.
    public static List<PricedOrderItem> UsdPricedItems()
    {
        return
        [
            new PricedOrderItem(KeyboardId, "Keyboard", 10m, "USD", 2),
            new PricedOrderItem(MouseId, "Mouse", 5m, "USD", 3),
        ];
    }

    public static Order Placed()
    {
        List<OrderLine> lines = [new OrderLine(KeyboardId, 2), new OrderLine(MouseId, 3)];
        Order order = Order.Place(UserId, lines, CreatedOnUtc).Value;

        SetId(order, OrderId);

        return order;
    }

    public static Order In(OrderStatus status)
    {
        Order order = Placed();

        if (status == OrderStatus.Placed)
        {
            return order;
        }

        if (status == OrderStatus.Cancelled)
        {
            AssertSuccess(order.Cancel(CustomerCancelReason, CreatedOnUtc));
            return order;
        }

        List<PricedOrderLine> prices =
        [
            new PricedOrderLine(KeyboardId, "Keyboard", new Money(10m, Currency.Usd)),
            new PricedOrderLine(MouseId, "Mouse", new Money(5m, Currency.Usd)),
        ];
        AssertSuccess(order.ConfirmStock(prices, CreatedOnUtc));

        if (status == OrderStatus.StockConfirmed)
        {
            return order;
        }

        AssertSuccess(order.MarkPaid(CreatedOnUtc));

        if (status == OrderStatus.Paid)
        {
            return order;
        }

        AssertSuccess(order.Ship(CreatedOnUtc));

        if (status == OrderStatus.Shipped)
        {
            return order;
        }

        AssertSuccess(order.Deliver(CreatedOnUtc));

        return order;
    }

    // Entity<long>.Id is init-only and normally generated by the database.
    public static void SetId(Order order, long id)
    {
        IdProperty.SetValue(order, id);
    }

    private static void AssertSuccess(Result result)
    {
        Assert.True(result.IsSuccess, $"Arranging the order failed: {result.Error.Name}");
    }
}
